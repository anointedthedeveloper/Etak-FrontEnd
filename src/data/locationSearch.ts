const PAGE_SIZE = 6

export function searchDestinations(query: string, page = 1): { results: SearchDestination[]; hasMore: boolean } {
  if (!query.trim()) return { results: [], hasMore: false }
  const q = query.toLowerCase()
  const all = searchDestinationList.filter(d =>
    d.city.toLowerCase().includes(q) ||
    d.country.toLowerCase().includes(q) ||
    d.region.toLowerCase().includes(q)
  )
  return { results: all.slice(0, page * PAGE_SIZE), hasMore: all.length > page * PAGE_SIZE }
}

export function getPopularDestinations(): SearchDestination[] {
  return searchDestinationList.filter(d => d.popular)
}
